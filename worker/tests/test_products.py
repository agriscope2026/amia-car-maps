@pytest.mark.parametrize("kind", ["rainfall_dekad", "rainfall_seasonal"])
def test_template_roundtrip(kind):
    name, data = templates.template(kind)
    df = pd.read_excel(io.BytesIO(data), sheet_name="DATA")
    assert len(df) == 77 and "README" in pd.ExcelFile(io.BytesIO(data)).sheet_names
    for c in df.columns[3:]:
        df[c] = 42.0
    if kind == "rainfall_dekad":
        p = rainfall_dekad.build(xlsx(df), name, DEKAD_SETTINGS)
    else:
        df["SEASON_TOTAL"] = 42.0 * 6
        df["PCT_NORMAL"] = 100.0
        p = rainfall_seasonal.build(xlsx(df), name, {"issue_date": "2026-09-30"})
    assert p["ok"], p["report"]["errors"][:3]
    assert p["report"]["n_unmatched"] == 0 and not p["report"]["missing_areas"]
    assert {m for m in p["report"]["methods"]} == {"exact"}


def test_drought_template_roundtrip():
    name, data = templates.template("drought")
    df = pd.read_csv(io.BytesIO(data), encoding="utf-8-sig")
    assert len(df) == 6 and list(df.columns[:2]) == ["ID", "PROVINCE"]
    for c in df.columns[2:]:
        df[c] = "dry spell"
    p = drought.build(df.to_csv(index=False).encode(), name, {"issue_date": "2026-09-15", "period_start": "2026-10"})
    assert p["ok"] and len(p["layers"]) == 6


# ----------------------------------------------------------------- exports ---

def test_exports_are_map_images_and_pdfs(tmp_path):
    p = rainfall_dekad.build(DEKAD.read_bytes(), DEKAD.name, DEKAD_SETTINGS)
    m = exports.export_product(p, tmp_path)
    assert m["labels_ok"] and len(m["maps"]) == 11                       # 10 daily maps + the 10-day total
    reps = json.loads((tmp_path / "label_report.json").read_text(encoding="utf-8"))
    assert all(r["placed"] == 83 and r["overlaps"] == [] for r in reps.values())
    from PIL import Image
    import zipfile
    mp = m["maps"][0]
    assert set(mp) == {"layer", "label", "alt", "png", "pdf", "jpg"}
    assert round(Image.open(tmp_path / mp["png"]).info["dpi"][0]) == 400
    assert (tmp_path / mp["pdf"]).read_bytes()[:4] == b"%PDF"
    assert max(Image.open(tmp_path / mp["jpg"]).size) == exports.PREVIEW_WIDTH       # sharp preview for photo mode
    assert list(m["files"]) == ["zip"]
    names = zipfile.ZipFile(tmp_path / m["files"]["zip"]).namelist()
    assert len(names) == 22 and all(n.endswith((".png", ".pdf")) for n in names)
    assert "CAR_rainfall_dekad_2026-10-01_png.png" in names


