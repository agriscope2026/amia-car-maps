# ----------------------------------------------------------------- classes ---

@pytest.mark.parametrize("v,label,desc", [(0, "0–5", "No Rain"), (4.99, "0–5", "No Rain"), (5, "5–15", "Very Light Rain"),
                                          (15, "15–37.5", "Light Rain"), (37.5, "37.5–75", "Moderate Rain"),
                                          (75, "75–150", "Heavy Rain"), (150, "150–250", "Intense Rain"),
                                          (250, "250–400", "Torrential Rain"), (400, "> 400", "Extreme Rain")])
def test_dekad_classes_at_breaks(v, label, desc):
    lg = classes.preset("rainfall_dekad")
    lab, _ = classes.assign(pd.Series([v]), lg)
    assert lab.iloc[0] == label
    assert next(c["desc"] for c in lg["classes"] if c["label"] == label) == desc


@pytest.mark.parametrize("v,label", [(0, "0–50"), (50, "50–100"), (499.9, "400–500"), (500, "> 500")])
def test_monthly_classes_at_breaks(v, label):
    assert classes.assign(pd.Series([v]), classes.preset("rainfall_month"))[0].iloc[0] == label


@pytest.mark.parametrize("v,word", [(39, "Way below"), (40, "Way below"), (41, "Below"), (80, "Below"),
                                    (81, "Near"), (120, "Near"), (121, "Above")])
def test_pct_normal_classes(v, word):
    assert classes.assign(pd.Series([v]), classes.preset("pct_normal"))[0].iloc[0].startswith(word)


def test_nan_is_no_data_and_custom_breaks():
    lg = classes.preset("rainfall_dekad", {"breaks": [0, 20, 40]})
    lab, col = classes.assign(pd.Series([np.nan, 5, 20, 99]), lg)
    assert lab.tolist() == ["No data", "0–20", "20–40", "> 40"] and col.iloc[0] == classes.NO_DATA_COLOR
    with pytest.raises(ValueError):
        classes.graduated("x", "x", "mm", [0, 10, 5], ["#000"] * 3)


# ------------------------------------------------------------------ dekad ---

def test_dekad_sample_builds_one_map_per_day():
    p = rainfall_dekad.build(DEKAD.read_bytes(), DEKAD.name, DEKAD_SETTINGS)
    assert p["ok"], p["report"]["errors"]
    ids = [lyr["id"] for lyr in p["layers"]]
    assert ids == [f"d_2026-10-{d:02d}" for d in range(1, 11)] + ["total"]
    assert [lyr["label"] for lyr in p["layers"][:2]] == ["October 1", "October 2"]
    assert p["valid_text"] == "Valid from October 1 – October 10, 2026"
    lyr = p["layers"][-1]
    assert len(lyr["values"]) == 77 and lyr["unit"] == "mm"
    assert p["period"]["label"] == "October 1–10, 2026" and len(p["period"]["days"]) == 10
    assert sum(c["count"] for c in lyr["legend"]["classes"]) == 77


def test_dekad_daily_columns_summed_and_errors_point_to_cells():
    df = pd.DataFrame({"PROVINCE": ["Abra", "Abra", "Benguet"], "MUNICIPALITY": ["Bangued", "Tubo", "Baguio City"],
                       "DAY_1": [1, 2, "x"], "DAY_2": [3, -1, 5]})
    p = rainfall_dekad.build(xlsx(df), "d.xlsx", DEKAD_SETTINGS)
    errs = " | ".join(p["report"]["errors"])
    assert "row 4, column DAY_1" in errs and "'x' is not a number" in errs
    assert "row 3, column DAY_2" in errs and "negative" in errs
    df.loc[1, "DAY_2"], df.loc[2, "DAY_1"] = 4, 0
    p = rainfall_dekad.build(xlsx(df), "d.xlsx", DEKAD_SETTINGS)
    assert p["ok"]
    v = p["layers"][-1]["values"]                       # 10-day total
    assert v["ABRA|BANGUED"]["value"] == 4 and v["BENGUET|BAGUIO"]["value"] == 5
    assert p["layers"][0]["values"]["ABRA|BANGUED"]["value"] == 1 and p["layers"][1]["values"]["ABRA|BANGUED"]["value"] == 3
    assert v["IFUGAO|BANAUE"]["class"] == "No data"
    assert any("74 of 77 municipalities are missing" in w for w in p["report"]["warnings"])


def test_dekad_subtotals_skipped_and_max_warning():
    df = pd.DataFrame({"MUNICIPALITY": ["CAR", "Abra", "Bangued", "Tubo"], "RAINFALL_MM": [9999, 999, 600, 20]})
    p = rainfall_dekad.build(xlsx(df), "d.xlsx", {**DEKAD_SETTINGS, "max_warn_mm": 500})
    assert p["ok"]
    assert p["report"]["n_subtotal_rows"] == 2
    assert [w for w in p["report"]["warnings"] if "above 500" in w] == [
        "row 4, column RAINFALL_MM: 600 mm is above 500 mm – please check."]


def test_dekad_requires_dates_and_column():
    p = rainfall_dekad.build(xlsx(pd.DataFrame({"MUNICIPALITY": ["Tubo"], "X": [1]})), "d.xlsx", {})
    assert not p["ok"] and any("DAY_1" in e for e in p["report"]["errors"])


def test_unmatched_row_has_suggestions_and_manual_assignment():
    df = pd.DataFrame({"PROVINCE": ["Abra"], "MUNICIPALITY": ["Atlantis"], "RAINFALL_MM": [12]})
    p = rainfall_dekad.build(xlsx(df), "d.xlsx", DEKAD_SETTINGS)
    un = p["report"]["unmatched"]
    assert len(un) == 1 and len(un[0]["suggestions"]) == 3
    p = rainfall_dekad.build(xlsx(df), "d.xlsx", {**DEKAD_SETTINGS,
                                                  "manual_matches": {"rainfall_dekad|Atlantis": "ABRA|TUBO"}})
    assert p["layers"][-1]["values"]["ABRA|TUBO"]["value"] == 12
    assert any("no daily maps" in w for w in p["report"]["warnings"])


