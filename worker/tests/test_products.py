def test_envi_exports_with_crop_circles(tmp_path):
    from PIL import Image
    from agriclimate.products.reference_layers import build_crops
    files = {k: (p.read_bytes(), p.name) for k, p in config.DEFAULT_FILES.items()}
    s = {"issue_date": "2026-09-15", "period_start": "2026-10", "period_end": "2027-03"}
    p = envi_product.build(files, s)
    c = build_crops(config.DEFAULT_FILES["crops"].read_bytes(), config.DEFAULT_FILES["crops"].name, {"as_of": "2026-09-15"})
    ov = {"as_of": c["as_of"], "crops": {"Rice": c["colors"]["Rice"]}, "values": c["values"]}
    m = exports.export_product(p, tmp_path, {**s, "crop_overlay": ov}, files)
    mp = m["maps"][0]
    assert m["labels_ok"]
    assert Image.open(tmp_path / mp["presentation"]).size == (5760, 3240)          # high-definition presentation
    assert Image.open(tmp_path / mp["poster"]).size == (3720, 5262)                # A4 at 450 dpi
    for k in ("presentation_pdf", "poster_pdf", "pdf"):
        assert (tmp_path / mp[k]).read_bytes()[:4] == b"%PDF"
    assert {"presentation_web", "poster_web"} <= set(mp)
